"""Faz 6 export: the Ollama Modelfile must not override the chat template embedded in the GGUF (the training template)."""
from pathlib import Path

from bist.finetune.to_ollama import modelfile

BASE = '''# Modelfile generated by "ollama show"
FROM C:\\blobs\\sha256-abc
TEMPLATE """{{- range .Messages }}
{{ .Content }}
{{- end }}"""
PARAMETER repeat_penalty 1
PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>
PARAMETER temperature 0.7
LICENSE """Apache
License"""
'''


def test_modelfile_keeps_params_and_drops_go_template(tmp_path):
    src = tmp_path / "m.gguf"
    mf = modelfile(src, BASE)
    assert mf.splitlines()[0] == f"FROM {src.resolve()}"
    assert "TEMPLATE" not in mf and "{{" not in mf and "LICENSE" not in mf
    assert [l for l in mf.splitlines() if l.startswith("PARAMETER")] == [
        "PARAMETER repeat_penalty 1", "PARAMETER stop <|im_start|>", "PARAMETER stop <|im_end|>", "PARAMETER temperature 0.7"]
